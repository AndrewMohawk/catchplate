#!/usr/bin/env python3
"""Fixed existing RuntimeTrust signer, never a runtime or attestation producer."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
USAGE = """Usage: python -I -B scripts/authority/local_runtime_trust.py --approval-fd N --approval-sha256 sha256:HEX --signing-key-fd N

Root-only local RuntimeTrustApproval/v1 or explicit v2, protected original plus sealed32
configuration-root key explicitly delegated for this exact runtime-trust domain.
Requires actual signed Service6 and verifier local-attestation originals, exact
selected payload/local generation/role references, boot and original clocks.
The verifier evidence is independently supplied, never generated by this signer.

V1 app/relay rosters remain prospective exact-list policy, NOT observations.
V2 keeps the app list and instead binds relay role/configuration/generation to
its genuine same-PID measured-launcher post-seal descriptor observation. No
caller roster override or guessed future relay numbers. Development only; all
consumers still require actual UID/GID, exact handles, current verifier evidence
and authenticated same-kernel Unix peers.
No PID, descriptor owner, startup receipt, package install, native/TEE guarantee
or off-host custody is created. Original approval and evidence bounds cannot renew.

Writes the existing signedPolicyAuthorityRuntimeTrust/v1 envelope as canonical
JSON without newline to a root-owned pipe. Require complete output AND exit0.
No file/state changes or retry; local root can access the key, and Python copies
are not hardware custody or guaranteed erased. Externally bound kernel stalls.
"""


def arguments(argv):
    if len(argv) != 6 or argv[::2] != ["--approval-fd", "--approval-sha256", "--signing-key-fd"]:
        raise ValueError("fixed runtime trust arguments required")
    values = {}
    for name, raw in (("approval_fd", argv[1]), ("signing_key_fd", argv[5])):
        value = int(raw)
        if str(value) != raw or not 3 <= value < 2**31:
            raise ValueError("descriptor refused")
        values[name] = value
    pin = argv[3]
    if len(pin) != 71 or not pin.startswith("sha256:") or any(c not in "0123456789abcdef" for c in pin[7:]):
        raise ValueError("approval pin refused")
    if values["approval_fd"] == values["signing_key_fd"]:
        raise ValueError("descriptor alias refused")
    return dict(values, approval_sha256=pin)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv == ["--help"]:
        print(USAGE, end=""); return 0
    try:
        selected = arguments(argv)
        from catchplate.authority_local_runtime_trust import LocalRuntimeTrustIssuer
        LocalRuntimeTrustIssuer(**selected).publish()
        return 0
    except BaseException:
        import os
        try: os.write(2, b"local runtime trust issuance refused; no retry or runtime admission claimed\n")
        except OSError: pass
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
