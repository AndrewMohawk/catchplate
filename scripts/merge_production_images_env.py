#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import run_production_readiness  # noqa: E402

KEY = "SERVERWARE_PRODUCTION_IMAGES"
IMAGE_REF_RE = re.compile(r"^(?P<repo>[^@,\s]+)@(?P<digest>sha256:[0-9a-f]{64})$")


def canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def load_env_assignments(path: Path) -> dict[str, str]:
    if not path.exists():
        raise FileNotFoundError(f"env file does not exist: {path}")
    loaded: dict[str, str] = {}
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        parsed = run_production_readiness.parse_env_assignment(raw, lineno)
        if parsed is None:
            continue
        key, value = parsed
        if key in loaded:
            raise ValueError(f"line {lineno}: duplicate environment key {key}")
        loaded[key] = value
    if not loaded:
        raise ValueError(f"env file is empty: {path}")
    return loaded


def load_images_fragment(path: Path) -> str:
    loaded = load_env_assignments(path)
    keys = sorted(loaded)
    if keys != [KEY]:
        raise ValueError(f"{path} must contain only {KEY}; found keys: {keys}")
    return loaded[KEY]


def validate_production_images(value: str) -> list[dict[str, str]]:
    refs = [item.strip() for item in value.split(",") if item.strip()]
    if not refs:
        raise ValueError(f"{KEY} must list at least one digest-pinned image ref")
    seen: set[str] = set()
    images: list[dict[str, str]] = []
    for ref in refs:
        if ref in seen:
            raise ValueError(f"duplicate production image ref: {ref}")
        seen.add(ref)
        match = IMAGE_REF_RE.fullmatch(ref)
        if not match:
            raise ValueError(f"production image ref must be repo@sha256:<64 hex>: {ref}")
        lowered = ref.lower()
        for marker in ("fixture", ":dev", ":local", ":test"):
            if marker in lowered:
                raise ValueError(f"production image ref must not contain {marker}: {ref}")
        repo = match.group("repo")
        if "/" not in repo:
            raise ValueError(f"production image ref must include a registry/repository path: {ref}")
        images.append(
            {
                "ref": ref,
                "repository": repo,
                "name": repo.rsplit("/", 1)[-1],
                "digest": match.group("digest"),
            }
        )
    return images


def find_assignment_lines(lines: list[str], key: str) -> list[int]:
    matches: list[int] = []
    for index, raw in enumerate(lines):
        parsed = run_production_readiness.parse_env_assignment(raw, index + 1)
        if parsed is None:
            continue
        parsed_key, _ = parsed
        if parsed_key == key:
            matches.append(index)
    return matches


def merge_env_text(existing: str, key: str, value: str) -> tuple[str, bool]:
    lines = existing.splitlines(keepends=True)
    matches = find_assignment_lines(lines, key)
    if len(matches) > 1:
        raise ValueError(f"target env file has duplicate {key} assignments")
    replacement = f"{key}={value}\n"
    if matches:
        lines[matches[0]] = replacement
    else:
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
        if lines and lines[-1].strip():
            lines.append("\n")
        lines.append("# Immutable production image digest refs generated by make publish-production-images.\n")
        lines.append(replacement)
    merged = "".join(lines)
    return merged, merged != existing


def redacted_summary(
    *,
    images_env: Path,
    env_file: Path,
    out: Path,
    images: list[dict[str, str]],
    env_keys: list[str],
    changed: bool,
    dry_run: bool,
) -> dict[str, Any]:
    return {
        "ok": True,
        "images_env": str(images_env),
        "env_file": str(env_file),
        "out": str(out),
        "dry_run": dry_run,
        "changed": changed,
        "production_images_count": len(images),
        "production_images": images,
        "target_env_keys": env_keys,
        "updated_key": KEY,
        "secret_values_redacted": True,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Merge published production image digest refs into a production readiness env file.")
    parser.add_argument("--images-env", default=".tmp/production-images.env")
    parser.add_argument("--env-file", default="ops/production-readiness.env")
    parser.add_argument("--out", default=None, help="Write to this path instead of updating --env-file in place.")
    parser.add_argument("--dry-run", action="store_true", help="Validate and print a redacted merge summary without writing.")
    args = parser.parse_args()

    images_env = Path(args.images_env)
    env_file = Path(args.env_file)
    out = Path(args.out) if args.out else env_file
    try:
        production_images_value = load_images_fragment(images_env)
        images = validate_production_images(production_images_value)
        target_assignments = load_env_assignments(env_file)
        existing = env_file.read_text(encoding="utf-8")
        merged, changed = merge_env_text(existing, KEY, production_images_value)
        if not args.dry_run:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(merged, encoding="utf-8")
        print(
            canonical_json(
                redacted_summary(
                    images_env=images_env,
                    env_file=env_file,
                    out=out,
                    images=images,
                    env_keys=sorted(set(target_assignments) | {KEY}),
                    changed=changed,
                    dry_run=args.dry_run,
                )
            )
        )
    except Exception as exc:
        print(canonical_json({"ok": False, "error": str(exc)}), file=sys.stderr)
        raise SystemExit(1) from exc


if __name__ == "__main__":
    main()
