// Offline controls for actual production JS with an inert DOM and closed fetch
// responses. No browser, HTTP, backend, storage service, consent or X request.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const ROOT = new URL('../', import.meta.url);
const ASSETS = new URL('serverware/operator_demo_web/', ROOT);
const SOURCE = ['workspace_core.js', 'workspace_upstreams.js', 'workspace_x_configuration.js']
  .map(name => readFileSync(new URL(name, ASSETS), 'utf8')).join('\n');
const HTML = readFileSync(new URL('index.html', ASSETS), 'utf8');
const PATH = '/api/operator-demo/oauth/x/configuration/v1';
const STORAGE = 'serverware.operator.x.configuration.operation.v1';
const ORIGIN = 'https://operator.example.com';
const CALLBACK = ORIGIN + '/api/oauth/callback/x';
const ID = '11111111-1111-4111-8111-111111111111';
const OTHER = '22222222-2222-4222-8222-222222222222';
const CLIENT = 'synthetic-X-client';
const SECRET = 'synthetic-X-secret-NEVER-RENDER-OR-STORE';
const PRIVATE = '<img src=x onerror="private-canary()"> private response https://private.invalid/?token=secret';
const SCOPES = ['offline.access', 'tweet.read', 'tweet.write', 'users.read'];
const digest = character => 'sha256:' + character.repeat(64);
const clone = value => JSON.parse(JSON.stringify(value));
// Independent literal server DTOs, not generated by production JS helpers.
const profile = (changes = {}) => ({schema: 'serverware.operatorXOAuthProfile/v1', profile: 'operator-x-oauth-v1',
  provider_id: 'x', client_id: CLIENT, redirect_uri: CALLBACK, client_auth_method: 'client_secret_basic',
  permission_preset: 'x_text_post_v1', scopes: [...SCOPES], api_origins: ['https://api.x.com'],
  authorization_url: 'https://x.com/i/oauth2/authorize', token_url: 'https://api.x.com/2/oauth2/token',
  revocation_url: 'https://api.x.com/2/oauth2/revoke', identity_url: 'https://api.x.com/2/users/me', ...changes});
const receipt = (changes = {}) => ({schema: 'serverware.operatorXConfigurationOperation/v1', operation_id: ID,
  status: 'committed', config_version: 1, committed_revision: 8, policy_hash: digest('a'),
  profile_binding_digest: digest('b'), public_profile: profile(), client_secret_configured: true, consent_ready: false, ...changes});
const discovery = (changes = {}) => ({schema: 'serverware.operatorXConfiguration/v1', state: 'unconfigured', revision: 7,
  policy_hash: digest('a'), redirect_uri: CALLBACK, permission_preset: 'x_text_post_v1', scopes: [...SCOPES],
  configuration: null, operation: null, review: {expected_revision: 7, expected_policy_hash: digest('a')},
  blocked_reason: null, consent_ready: false, ...changes});
function configured(operation = receipt(), changes = {}) {
  return discovery({state: 'configured', revision: operation.committed_revision,
    configuration: {config_version: 1, profile_binding_digest: operation.profile_binding_digest,
      public_profile: clone(operation.public_profile), client_secret_configured: true},
    operation: clone(operation), review: null, blocked_reason: 'already_configured', ...changes});
}
class Node {
  constructor(id) { this.id = id; this.value = ''; this.textContent = ''; this.hidden = false; this.disabled = false; this.events = new Map(); }
  addEventListener(name, callback) { const list = this.events.get(name) || []; list.push(callback); this.events.set(name, list); }
  insertBefore(node, before) { this.inserted = {node: node.id, before: before.id}; }
  querySelectorAll() { return []; }
  set innerHTML(_) { throw new Error('HTML rendering forbidden'); }
}
const response = (value, status = 200, {raw, type = 'application/json'} = {}) => ({
  ok: status >= 200 && status < 300, status, headers: {get: name => name.toLowerCase() === 'content-type' ? type : null},
  async text() { return raw === undefined ? JSON.stringify(value) : raw; },
});
const deferred = () => { let resolve; let reject; const promise = new Promise((yes, no) => { resolve = yes; reject = no; }); return {promise, resolve, reject}; };

function fixture(options = {}) {
  const nodes = new Map([...HTML.matchAll(/\bid="([^"]+)"/g)].map(match => [match[1], new Node(match[1])]));
  nodes.set('proxy-setup-content', new Node('proxy-setup-content'));
  const node = id => { assert(nodes.has(id), 'Missing production element'); return nodes.get(id); };
  const storage = new Map(Object.entries(options.storage || {})); const writes = []; const calls = []; const copied = [];
  const serializedPayloads = []; const windowEvents = new Map(); const forbidden = [];
  const state = {discovery: clone(options.discovery || discovery()), operation: options.operation ? clone(options.operation) : null,
    discoveryGets: 0, refreshes: 0};
  const deny = kind => () => { forbidden.push(kind); throw new Error('Forbidden fixture effect'); };
  const checkTransport = check => {
    try { check(); } catch (error) { forbidden.push('fetch-contract'); throw error; }
  };
  const fetch = (path, init) => {
    const method = init.method || 'GET';
    checkTransport(() => {
      assert.equal(init.credentials, 'same-origin'); assert.equal(init.cache, 'no-store'); assert.equal(init.redirect, 'error');
      assert.equal(typeof path, 'string'); assert(!path.includes(SECRET)); assert(!path.includes(CLIENT));
      assert(path === PATH || path === PATH + '/' + ID || path === PATH + '/' + OTHER, 'No provider/consent/restart/other API');
      assert(['GET', 'POST'].includes(method));
    });
    const body = init.body === undefined ? null : JSON.parse(init.body);
    calls.push({path, method, body});
    if (method === 'GET') {
      checkTransport(() => { assert.equal(body, null); assert.equal(init.headers, undefined); });
      if (path === PATH) {
        state.discoveryGets++;
        return Promise.resolve(options.onDiscovery?.(state) ?? response(state.discovery));
      }
      return Promise.resolve(options.onRecovery?.(path, state) ?? (state.operation ? response(state.operation) : response({detail: PRIVATE}, 404)));
    }
    checkTransport(() => {
      assert.equal(method, 'POST'); assert.equal(path, PATH);
      assert.deepEqual(clone(init.headers), {'Content-Type': 'application/json'});
      assert.equal(storage.get(STORAGE), body.operation_id, 'Public UUID retained before POST');
    });
    if (options.onPost) return options.onPost(body, state);
    state.operation = receipt({public_profile: profile({client_id: body.client_id})});
    state.discovery = configured(state.operation);
    return Promise.resolve(response(state.operation, 201));
  };
  const context = vm.createContext({URL, Date, TextEncoder,
    location: {origin: ORIGIN, protocol: 'https:', hash: ''},
    document: {getElementById: node}, element: node,
    window: {addEventListener(name, callback) { const list = windowEvents.get(name) || []; list.push(callback); windowEvents.set(name, list); }},
    sessionStorage: {getItem(key) { if (options.storageReadFailure) throw new Error(PRIVATE); return storage.get(key) ?? null; },
      setItem(key, value) { if (options.storageWriteFailure) throw new Error(PRIVATE); writes.push({key, value}); storage.set(key, value); },
      removeItem(key) { if (options.storageRemoveFailure) throw new Error(PRIVATE); writes.push({key, removed: true}); storage.delete(key); }},
    localStorage: {getItem: deny('localStorage'), setItem: deny('localStorage'), removeItem: deny('localStorage')},
    navigator: {clipboard: {async writeText(value) { copied.push(value); }}},
    crypto: {randomUUID() { if (options.uuidFailure) throw new Error(PRIVATE); return ID; }},
    AbortSignal: {timeout(milliseconds) { assert.equal(milliseconds, 30000); return {}; }},
    JSON: {parse: JSON.parse, stringify(value, ...args) {
      if (value && Object.hasOwn(value, 'client_secret')) serializedPayloads.push(value);
      return JSON.stringify(value, ...args);
    }}, fetch, setTimeout: deny('timer'), clearTimeout() {}, console: {log: deny('console'), error: deny('console')},
  });
  vm.runInContext(SOURCE, context, {timeout: 2000});
  const run = (expression, value) => { context.input = value; return vm.runInContext(expression, context, {timeout: 1000}); };
  const workspace = run('createOperatorWorkspace()');
  const catalog = () => ({revision: state.discovery.revision, policy: {policy_hash: state.discovery.policy_hash,
    loaded_policy_hash: state.discovery.policy_hash, activation: 'active'}});
  workspace.state.catalog = catalog();
  // Only catalog transport is synthetic; busy/uncertain, emit, requireReview,
  // named holds and explicit review acknowledgement are the real controller.
  workspace.refresh = async () => { state.refreshes++; workspace.state.catalog = catalog(); workspace.emit(); return true; };
  context.workspaceFixture = workspace;
  const view = run('createXConfigurationView(workspaceFixture)');
  const event = (id, name = 'click') => {
    const target = node(id); const handlers = target.events.get(name); assert(handlers?.length, 'Registered production handler');
    return Promise.all(handlers.map(handler => handler({preventDefault() {}, currentTarget: target})));
  };
  const windowEvent = name => Promise.all((windowEvents.get(name) || []).map(callback => callback()));
  const fill = async (secret = SECRET, client = CLIENT) => {
    node('x-configuration-client-id').value = client; node('x-configuration-client-secret').value = secret;
    await event('x-configuration-client-secret', 'input');
  };
  const posts = () => calls.filter(call => call.method === 'POST');
  const clean = () => {
    assert.equal(node('x-configuration-client-secret').value, '');
    for (const payload of serializedPayloads) assert.equal(payload.client_secret, '');
    for (const value of [...storage.values(), ...writes.map(item => item.value || ''), ...copied,
      ...[...nodes.values()].map(item => item.textContent)]) {
      assert(!value.includes(SECRET)); assert(!value.includes(PRIVATE));
    }
    for (const {key, value} of writes) { assert.equal(key, STORAGE); if (value !== undefined) assert.equal(value, ID); }
    assert.deepEqual(forbidden, []);
  };
  return {options, state, nodes, node, storage, writes, calls, copied, serializedPayloads, workspace, view,
    event, windowEvent, fill, posts, clean, run, start: () => view.show(true)};
}

