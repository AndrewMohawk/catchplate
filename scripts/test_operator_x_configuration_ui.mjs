let group = 'arguments';
try {
  assert.equal(process.argv.length, 2, 'No browser/live/execution arguments accepted');
  for (const [name, test] of tests) { group = name; await test(); process.stdout.write('PASS ' + name + '\n'); }
  process.stdout.write(JSON.stringify({ok: true, groups: tests.length, browser: false, network: false,
    scope: 'actual JS with inert DOM and independent synthetic API DTOs; not backend, browser or provider acceptance'}) + '\n');
} catch (error) {
  // Assertions can include serialized private fixture payloads. Report only
  // our fixed group name and numeric frames from this one source file.
  const file = fileURLToPath(import.meta.url);
  const frames = String(error?.stack || '').split('\n').filter(line => line.includes(file))
    .map(line => /:(\d+):(\d+)\)?$/.exec(line)).filter(Boolean).slice(0, 6)
    .map(match => ({line: Number(match[1]), column: Number(match[2])}));
  process.stderr.write(JSON.stringify({ok: false, group, frames}) + '\n'); process.exitCode = 1;
}
